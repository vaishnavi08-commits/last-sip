const GENERIC: string[] = [
  "{name} is running low.",
  "Down to your last bit of {name}.",
  "Not much {name} left.",
  "Running low on {name}.",
  "{name} levels are dropping.",
  "Almost out of {name}.",
  "Your {name} stock is thinning.",
  "Last of the {name} is going fast.",
  "{name} is nearly gone.",
  "Time to restock {name}.",
];

export function pickMessage(catalogId: string | null, name: string, petName: string | null): string {
  const variants = (catalogId && MESSAGES[catalogId]) || GENERIC;
  const chosen = variants[Math.floor(Math.random() * variants.length)];
  const pet = petName || name;
  return chosen
    .replace(/\{petPoss\}/g, possessive(pet))
    .replace(/\{pet\}/g, pet)
    .replace(/\{name\}/g, name);
}
